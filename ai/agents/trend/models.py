class EvidenceState(str, Enum):
    """
    Lifecycle state of a piece of trend evidence.
    """

    DEVELOPING = "DEVELOPING"
    CONFIRMED = "CONFIRMED"
    LOCKED = "LOCKED"
    INVALIDATED = "INVALIDATED"


# =============================================================================
# CHART EVIDENCE
# =============================================================================


@dataclass(slots=True)
class TrendEvidence:
    """
    Structured evidence generated by the Trend Agent.

    This is deliberately independent from the frontend. The frontend
    can convert this object into a chart annotation/overlay.
    """

    evidence_type: TrendEvidenceType

    state: EvidenceState = EvidenceState.DEVELOPING

    confidence: float = 0.0

    start_index: int | None = None

    end_index: int | None = None

    start_price: float | None = None

    end_price: float | None = None

    start_timestamp: object | None = None

    end_timestamp: object | None = None

    direction: str | None = None

    label: str | None = None

    reason: str | None = None

    source: str = "trend"

    locked: bool = False


# =============================================================================
# TREND STRUCTURE
