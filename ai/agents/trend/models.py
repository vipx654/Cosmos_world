# =============================================================================
# TREND SCORE
# =============================================================================


@dataclass(slots=True)
class TrendScore:
    """
    Internal confidence scoring.

    Each component remains independently inspectable so the final
    confidence can be explained and audited.
    """

    structure_score: float = 0.0

    momentum_score: float = 0.0

    ema_score: float = 0.0

    trendline_score: float = 0.0

    total_score: float = 0.0

    confluence_score: float = 0.0

    penalty_score: float = 0.0

    quality_score: float = 0.0

    sample_size: int = 0

    def calculate_total(self) -> float:
        """
        Calculate normalized total score.

        The individual engine scores are expected to be in the
        0-100 range.
        """

        weighted = (
            self.structure_score * 0.30
            + self.momentum_score * 0.25
            + self.ema_score * 0.20
            + self.trendline_score * 0.15
            + self.confluence_score * 0.10
        )

        weighted -= self.penalty_score

        self.total_score = max(
            0.0,
            min(
                100.0,
                weighted,
            ),
        )

        return self.total_score


# =============================================================================
# TREND SNAPSHOT
# =============================================================================


@dataclass(slots=True)
class TrendSnapshot:
    """
    Immutable-style snapshot of the Trend Agent's current conclusion.

    Downstream agents can consume this without needing to understand
    individual Trend engines.
    """

    regime: TrendRegime = TrendRegime.UNKNOWN

    bias: str = "NEUTRAL"

    confidence: float = 0.0

    strength: float = 0.0

    momentum: float = 0.0

    acceleration: bool = False

    structure: list[StructureType] = field(
        default_factory=list
    )

    evidence: list[TrendEvidence] = field(
        default_factory=list
    )

    locked: bool = False